// Helper: Extract Embed URLs for YouTube, Vimeo, or Direct Video
export function parseVideoEmbed(url) {
  if (!url || typeof url !== 'string') return null;
  url = url.trim();

  // 1. YouTube Matcher
  const ytMatch = url.match(/(?:youtube\.com\/(?:[^\/]+\/.+\/|(?:v|e(?:mbed)?)\/|.*[?&]v=)|youtu\.be\/|youtube\.com\/shorts\/)([^"&?\/\s]{11})/i);
  if (ytMatch && ytMatch[1]) {
    return {
      type: 'youtube',
      id: ytMatch[1],
      embedUrl: `https://www.youtube-nocookie.com/embed/${ytMatch[1]}?autoplay=1&rel=0&modestbranding=1`
    };
  }

  // 2. Vimeo Matcher
  const vimeoMatch = url.match(/vimeo\.com\/(?:channels\/(?:\w+\/)?|groups\/([^\/]*)\/videos\/|album\/(\d+)\/video\/|)(\d+)/i);
  if (vimeoMatch && vimeoMatch[3]) {
    return {
      type: 'vimeo',
      id: vimeoMatch[3],
      embedUrl: `https://player.vimeo.com/video/${vimeoMatch[3]}?autoplay=1&title=0&byline=0&portrait=0`
    };
  }

  // 3. Direct Video File
  if (url.match(/\.(mp4|webm|mov|ogg)($|\?)/i) || url.startsWith('/uploads/')) {
    return {
      type: 'direct',
      embedUrl: url
    };
  }

  if (url.startsWith('http')) {
    return {
      type: 'iframe',
      embedUrl: url
    };
  }

  return null;
}

export function setPortfolioData(projects) {
  if (Array.isArray(projects)) {
    hasCmsHydrated = true;
    portfolioData = projects.map(p => {
      let swList = [];
      if (Array.isArray(p.software)) {
        swList = p.software;
      } else if (typeof p.software_json === 'string') {
        try { swList = JSON.parse(p.software_json || '[]'); } catch { swList = []; }
      }

      const defaultMatch = DEFAULT_PROJECTS.find(dp => dp.id === p.id || dp.slug === p.slug) || {};

      return {
        id: p.id,
        slug: p.slug || p.id,
        title: p.title,
        category: p.category,
        categoryName: p.category_name || p.categoryName || p.category,
        aspectRatio: p.aspect_ratio || p.aspectRatio || '16-9',
        duration: p.duration || '02:00',
        summary: p.summary || '',
        client: p.client || 'Client Project',
        software: swList.length > 0 ? swList : (defaultMatch.software || ['Adobe Premiere Pro']),
        deliverable: p.deliverable || '4K Master Deliverable',
        soundDesign: p.sound_design || p.soundDesign || 'Custom Foley & SFX',
        colorGradingNote: p.color_note || p.colorGradingNote || 'Cinematic Grade',
        videoUrl: p.video_url || p.videoUrl || 'https://www.youtube.com/watch?v=dQw4w9WgXcQ',
        thumbnail: p.thumbnail || defaultMatch.thumbnail || '',
        gradient: defaultMatch.gradient || 'linear-gradient(135deg, #101018 0%, #1c1c28 100%)',
        accentColor: defaultMatch.accentColor || '#ffffff',
        badge: defaultMatch.badge || (p.category_name || 'PROJECT').toUpperCase()
      };
    });
  }
}

export function initPortfolio(customProjects = null) {
  const grid = document.getElementById('project-grid');
  const filterBtns = document.querySelectorAll('.portfolio-filters .filter-pill-btn');
  const modal = document.getElementById('project-detail-modal');
  const closeBtn = document.getElementById('modal-close-btn');
  const mediaContainer = document.getElementById('modal-media-container');
  
  if (customProjects) setPortfolioData(customProjects);
  if (!grid) return;

  function matchesProjectFilter(project, filter) {
    if (!filter || filter === 'all') return true;
    const f = filter.toLowerCase().trim();
    const cat = (project.category || '').toLowerCase().trim();
    const title = (project.title || '').toLowerCase().trim();

    if (f === 'video-editing') {
      return cat.includes('video') || cat.includes('edit') || cat.includes('color');
    }
    if (f === 'motion-graphics') {
      return cat.includes('motion') || cat.includes('graphic') || cat.includes('vfx') || cat.includes('3d');
    }
    if (f === 'youtube') {
      return cat.includes('youtube') || cat.includes('doc') || title.includes('youtube');
    }
    if (f === 'shorts') {
      return cat.includes('short') || cat.includes('reel') || cat.includes('tiktok') || project.aspectRatio === '9-16';
    }
    if (f === 'gaming') {
      return cat.includes('gaming') || cat.includes('montage') || title.includes('gaming');
    }
    if (f === 'thumbnails') {
      return cat.includes('thumb') || cat.includes('design') || title.includes('thumbnail');
    }

    return cat.includes(f) || title.includes(f);
  }

  function renderProjects(filter = 'all') {
    const list = hasCmsHydrated ? portfolioData : (portfolioData.length > 0 ? portfolioData : DEFAULT_PROJECTS);
    const filtered = list.filter(p => matchesProjectFilter(p, filter));

    if (filtered.length === 0) {
      grid.innerHTML = `<div style="grid-column: 1 / -1; text-align: center; padding: 3rem; color: var(--text-muted); font-size: 1.05rem;">No portfolio projects found for this filter.</div>`;
      return;
    }

    grid.innerHTML = filtered.map(item => {
      const isVertical = item.aspectRatio === '9-16';
      const videoInfo = parseVideoEmbed(item.videoUrl);
      
      let thumbImg = item.thumbnail;
      if (!thumbImg && videoInfo && videoInfo.type === 'youtube') {
        thumbImg = `https://img.youtube.com/vi/${videoInfo.id}/hqdefault.jpg`;
      }

      return `
        <div class="project-card interactive ${isVertical ? 'vertical-format' : ''} reveal-on-scroll" data-project-id="${item.id}">
          <div class="project-media-wrapper">
            <div class="project-aspect-ratio ${isVertical ? 'ar-9-16' : 'ar-16-9'}">
              ${thumbImg ? `<img src="${thumbImg}" alt="${item.title}" class="project-thumb-img" loading="lazy">` : `
              <div class="project-art-canvas" style="background: ${item.gradient || 'linear-gradient(135deg, #101018 0%, #1c1c28 100%)'};">
                <div class="project-art-pattern"></div>
                <div class="project-art-hud">
                  <span class="project-art-badge" style="border-color: ${item.accentColor || '#fff'}; color: ${item.accentColor || '#fff'};">${item.badge || 'CINEMATIC'}</span>
                  <div class="project-art-center-play">
                    <svg width="28" height="28" viewBox="0 0 24 24" fill="${item.accentColor || '#fff'}"><polygon points="6 3 20 12 6 21 6 3"></polygon></svg>
                  </div>
                  <div class="project-art-bottom">
                    <span class="project-art-code">SEQ // 4K MASTER</span>
                    <span class="project-art-fps">60 FPS</span>
                  </div>
                </div>
              </div>
              `}
            </div>

            <div class="project-hover-overlay">
              <div class="project-play-icon">
                <svg width="24" height="24" viewBox="0 0 24 24" fill="currentColor">
                  <polygon points="5 3 19 12 5 21 5 3"></polygon>
                </svg>
              </div>
              <span style="font-family: var(--font-mono); font-size: 0.8rem; letter-spacing: 1px;">WATCH VIDEO &amp; SPECS</span>
            </div>

            <div class="project-badge-top-left">${item.categoryName || 'Video'}</div>
            <div class="project-duration-badge">${item.duration}</div>
          </div>

          <div class="project-card-footer">
            <div class="project-client-line">${item.client}</div>
            <h3 class="project-title">${item.title}</h3>
            <p class="project-summary">${item.summary}</p>

            <div class="project-tags">
              ${(item.software || []).map(sw => `<span class="project-tag">${sw}</span>`).join('')}
            </div>
          </div>
        </div>
      `;
    }).join('');

    // Attach click triggers to open project detail modal
    grid.querySelectorAll('.project-card').forEach(card => {
      card.addEventListener('click', () => {
        const pId = card.getAttribute('data-project-id');
        const project = portfolioData.find(p => p.id === pId) || DEFAULT_PROJECTS.find(p => p.id === pId);
        if (project) openProjectModal(project);
      });
    });

    // Trigger reveal
    setTimeout(() => {
      grid.querySelectorAll('.reveal-on-scroll').forEach(el => el.classList.add('revealed'));
    }, 30);
  }

  function openProjectModal(p) {
    if (!modal) return;

    // Populate modal fields
    const titleEl = document.getElementById('modal-project-title');
    const clientEl = document.getElementById('modal-project-client');
    const softwareEl = document.getElementById('modal-project-software');
    const descEl = document.getElementById('modal-project-desc');
    const deliverableEl = document.getElementById('modal-project-deliverable');
    const soundEl = document.getElementById('modal-project-sound');
    const gradeEl = document.getElementById('modal-project-grade');

    if (titleEl) titleEl.textContent = p.title;
    if (clientEl) clientEl.textContent = p.client || 'Apex Horizon Studios';
    if (softwareEl) softwareEl.textContent = Array.isArray(p.software) ? p.software.join(', ') : 'Adobe Premiere Pro, After Effects';
    if (descEl) descEl.textContent = p.summary || 'Professional high-impact cinematic project by Rahat Khan.';
    if (deliverableEl) deliverableEl.textContent = p.deliverable || '4K UHD (3840x2160) @ 60fps';
    if (soundEl) soundEl.textContent = p.soundDesign || '5.1 Surround Sound Design & Dialogue Mastering';
    if (gradeEl) gradeEl.textContent = p.colorGradingNote || 'Custom cinematic film print curve with 35mm grain.';

    // Inject video embed
    if (mediaContainer) {
      const videoInfo = parseVideoEmbed(p.videoUrl);
      if (videoInfo && (videoInfo.type === 'youtube' || videoInfo.type === 'vimeo' || videoInfo.type === 'iframe')) {
        mediaContainer.innerHTML = `
          <iframe 
            src="${videoInfo.embedUrl}" 
            title="${p.title}" 
            frameborder="0" 
            allow="accelerometer; autoplay; clipboard-write; encrypted-media; gyroscope; picture-in-picture" 
            allowfullscreen
            style="width: 100%; height: 100%; aspect-ratio: 16/9; border: none;">
          </iframe>
        `;
      } else if (videoInfo && videoInfo.type === 'direct') {
        mediaContainer.innerHTML = `
          <video controls autoplay style="width: 100%; height: 100%; max-height: 480px; background: #000;">
            <source src="${videoInfo.embedUrl}">
            Your browser does not support video tag.
          </video>
        `;
      } else {
        mediaContainer.innerHTML = `
          <div style="width: 100%; height: 320px; background: ${p.gradient || '#121218'}; display: flex; flex-direction: column; align-items: center; justify-content: center; color: #fff;">
            <div style="font-family: var(--font-heading); font-size: 1.5rem; font-weight: 700; margin-bottom: 8px;">${p.title}</div>
            <div style="font-family: var(--font-mono); font-size: 0.85rem; color: var(--text-muted);">${p.deliverable}</div>
          </div>
        `;
      }
    }

    modal.classList.add('active');
    document.body.style.overflow = 'hidden';
    if (window.playUiSound) window.playUiSound('whoosh');
  }

  function closeModal() {
    if (!modal) return;
    modal.classList.remove('active');
    document.body.style.overflow = '';
    if (mediaContainer) mediaContainer.innerHTML = '';
    if (window.playUiSound) window.playUiSound('click');
  }

  if (closeBtn) closeBtn.addEventListener('click', closeModal);
  if (modal) {
    modal.addEventListener('click', (e) => {
      if (e.target === modal) closeModal();
    });
  }

  window.addEventListener('keydown', (e) => {
    if (e.key === 'Escape' && modal && modal.classList.contains('active')) {
      closeModal();
    }
  });

  filterBtns.forEach(btn => {
    btn.addEventListener('click', (e) => {
      e.preventDefault();
      filterBtns.forEach(b => b.classList.remove('active'));
      btn.classList.add('active');
      const filter = btn.getAttribute('data-filter');
      renderProjects(filter);
      if (window.playUiSound) window.playUiSound('click');
    });
  });

  renderProjects('all');
}
